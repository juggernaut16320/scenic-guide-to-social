def build_single_prompt(platform: str, style: str = "", custom_style: str = "") -> str:
    base = SINGLE_PROMPTS.get(platform, SINGLE_PROMPTS["xiaohongshu"])

    # 风格描述：自定义 > 预设
    if custom_style.strip():
        style_desc = f"整体语气和文风必须严格遵循：{custom_style.strip()}"
    else:
        if platform == "xiaohongshu":
            style_desc = XHS_STYLES.get(style, XHS_STYLES["种草探店"])
        elif platform == "douyin":
            style_desc = DY_STYLES.get(style, DY_STYLES["正经解说"])
        elif platform == "pengyouquan":
            style_desc = PYQ_STYLES.get(style, PYQ_STYLES["文艺清新"])
        else:
            style_desc = ""

    return base.format(style_desc=style_desc)


